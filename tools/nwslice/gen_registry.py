#!/usr/bin/env python3
"""Merge the SerializeContext schema dump + name tables into nw_registry.json,
the intermediate descriptor the slice tools (and later the AP plugin) consume.

Inputs (defaults):
  --schema  /mnt/dev_scratch/newworld/tools/ghidra/index_mcp/az_serialize_names.json
  --uuids   tools/nwslice/uuid_names.json
  --crcs    tools/nwslice/crc_names.json
Output:
  tools/nwslice/nw_registry.json

Registry shape:
  types:  {"<typeId lower>": {"name","bases","fields":[{name,offset,size,type,is_base,is_ptr}]}}
          classes from the schema dump, plus name-only entries from uuid_names
  field_names: {"%08x": "name"}  crc32(lower(name)) -> name, from schema fields
          + crc_names.json (verified: AZ field crc = zlib.crc32 of the
          lowercased name, matching all 214 known pairs)
  type_names: {"<uuid lower>": "name"}  flat typeId -> name map for lookups
"""
import argparse, json, os, zlib

HERE = os.path.dirname(os.path.abspath(__file__))


def build(schema_path, uuids_path, crcs_path):
    schema = json.load(open(schema_path))
    uuids = json.load(open(uuids_path))['names']
    crc_names = json.load(open(crcs_path))

    types = {}
    for tid, name in uuids.items():
        types[tid.lower()] = {'name': name, 'bases': [], 'fields': []}
    field_names = {h.lower(): n for h, n in crc_names.items()}
    for c in schema['class_fields']:
        entry = {'name': c['name'], 'bases': c.get('bases', []),
                 'fields': c.get('fields', []), 'typeId': c['typeId'].lower()}
        types[c['typeId'].lower()] = entry
        for f in entry['fields']:
            n = f.get('name')
            if n:
                h = '%08x' % (zlib.crc32(n.lower().encode()) & 0xffffffff)
                if h in field_names and field_names[h] != n:
                    pass  # same-string or rare collision; first wins
                else:
                    field_names[h] = n
    type_names = {tid: t['name'] for tid, t in types.items() if t.get('name')}
    return {'_doc': 'generated by gen_registry.py — do not edit',
            'types': types, 'field_names': field_names,
            'type_names': type_names,
            'counts': {'types': len(types), 'fields': len(field_names)}}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--schema', default='/mnt/dev_scratch/newworld/tools/ghidra/index_mcp/az_serialize_names.json')
    ap.add_argument('--uuids', default=os.path.join(HERE, 'uuid_names.json'))
    ap.add_argument('--crcs', default=os.path.join(HERE, 'crc_names.json'))
    ap.add_argument('--out', default=os.path.join(HERE, 'nw_registry.json'))
    a = ap.parse_args()
    reg = build(a.schema, a.uuids, a.crcs)
    with open(a.out, 'w') as f:
        json.dump(reg, f, separators=(',', ':'))
    print('wrote %s: %d types, %d field names' % (a.out, reg['counts']['types'], reg['counts']['fields']))


if __name__ == '__main__':
    main()
